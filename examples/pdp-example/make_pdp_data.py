"""Builds pdp_data.py for the PDP template example from the Friendly Skies Enverus pull (deals/friendly-skies),
pulled 2026-11-23 via the Enverus connector. Subject: the six King 3-65 28-29 wells (SM Energy, Niobrara A/B,
Adams Co CO, first production 2024-10). Offsets: every other Niobrara well in that pull whose lateral midpoint is
within 5 miles of the King pad's lateral midpoints. Interests are hypothetical (example only)."""
import importlib.util, json, math, os
H = os.path.dirname(os.path.abspath(__file__)); FS = os.path.join(H, "..", "..", "deals", "friendly-skies")
spec = importlib.util.spec_from_file_location("d", os.path.join(FS, "deal_data.py")); d = importlib.util.module_from_spec(spec); spec.loader.exec_module(d)
hdr = {}
for f in ("offsets_15mi.json", "offsets_12p5mi.json"):
    for r in json.load(open(os.path.join(FS, f))):
        hdr.setdefault(r["API_UWI"].replace("-", ""), r)
mid = lambda r: ((float(r["Latitude"]) + float(r["Latitude_BH"])) / 2, (float(r["Longitude"]) + float(r["Longitude_BH"])) / 2)
subj = [a for a, v in d.WELLS.items() if v[0].startswith("KING 3-65 28-29")]
pts = [mid(hdr[a]) for a in subj]
c = (sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts))
dist = lambda p: 3958.8 * 2 * math.asin(math.sqrt(math.sin(math.radians(p[0] - c[0]) / 2) ** 2 + math.cos(math.radians(c[0])) * math.cos(math.radians(p[0])) * math.sin(math.radians(p[1] - c[1]) / 2) ** 2))
L = ["# Generated by make_pdp_data.py from the Friendly Skies Enverus pull (2026-11-23; production through 2026-08).",
     "# EXAMPLE ONLY: the King 3-65 28-29 pad (SM Energy, Niobrara A/B, Adams Co CO) priced as if offered as a PDP package;",
     "# interests are hypothetical. Offsets: Niobrara A/B/C, lateral midpoint within 5 mi of the pad's centroid "
     f"({c[0]:.4f}, {c[1]:.4f}).",
     'DEAL = dict(name="King 28-29 PDP (example)", basin="DJ (CO)", deal_type="Working interest", effective="2026-12",',
     '            asking_price=2500000, operator="SM ENERGY")',
     f'LAST_MONTH = "{d.LAST_MONTH}"',
     "# api: (well, lateral_ft, first_month, oil_bbl[], gas_mcf[], zone, wi, nri, lease_nri)",
     "SUBJECT = {"]
for a in subj:
    v = d.WELLS[a]
    L.append(f'"{a}": ({v[0]!r}, {v[1]}, "{v[2]}", {list(v[3])}, {list(v[4])}, {v[5]!r}, 0.10, 0.08, 0.80),')
L += ["}", "# api: (well, lateral_ft, first_month, oil_bbl[], gas_mcf[], zone, distance_mi)", "OFFSETS = {"]
n = 0
for a, v in d.WELLS.items():
    if a in subj or a not in hdr:
        continue
    dm = dist(mid(hdr[a]))
    if dm <= 5:
        L.append(f'"{a}": ({v[0]!r}, {v[1]}, "{v[2]}", {list(v[3])}, {list(v[4])}, {v[5]!r}, {dm:.2f}),'); n += 1
L += ["}", 'ZONE_GROUPS = {"NIOBRARA A": "Niobrara", "NIOBRARA B": "Niobrara", "NIOBRARA C": "Niobrara"}',
      "DAYS = {" + ", ".join(f'"{a}": {list(d.DAYS[a])}' for a in d.WELLS if a in d.DAYS) + "}"]
open(os.path.join(H, "pdp_data.py"), "w").write("\n".join(L) + "\n")
print(len(subj), "subject wells,", n, "offsets within 5 mi; centroid", c)
