"""Builds pdp_data.py for the Madison-Hamill 36A-36D PDP package (XTO / Exxon, Wolfcamp A, Martin Co TX).
Raw Enverus pulls in raw/ (2026-11-24 via the Enverus connector): offsets_5mi.json (offset_wells, 5 mi of the lateral-midpoint
centroid), selection.json (screen), prod_*.json (production dataset: liquids, gas, ProducingDays).
Interests from Davis (2026-11-24). Lease NRI for the 8/8 economic limit: 75% (assumption; Texas fee leases)."""
import csv, glob, io, json, os
H = os.path.dirname(os.path.abspath(__file__))
SUBJ = {"4231743215": (0.144782, 0.140258), "4231743216": (0.144434, 0.13992), "4231743217": (0.144724, 0.140202), "4231743218": (0.14455, 0.140033)}
LEASE_NRI = 0.75
off = {r["API_UWI"].replace("-", ""): r for r in json.load(open(os.path.join(H, "raw", "offsets_5mi.json")))}
sel = json.load(open(os.path.join(H, "raw", "selection.json")))
prod = {}
for f in glob.glob(os.path.join(H, "raw", "prod_*.json")):
    t = json.load(open(f))[0]["text"].split("\n", 1)[1]
    for r in csv.DictReader(io.StringIO(t)):
        prod.setdefault(r["API_UWI_Unformatted"], {})[r["ProducingMonth"][:7]] = (float(r["LiquidsProd_BBL"] or 0), float(r["GasProd_MCF"] or 0), int(float(r["ProducingDays"] or 0)) if r["ProducingDays"] else None)
# last month every subject well reports
LAST = min(max(prod[a]) for a in SUBJ)
def series(a, last):
    p = prod[a]; first = r_first = off[a]["FirstProdDate"][:7]
    months = sorted(m for m in p if m <= last)
    first = min(m for m in months if p[m][0] + p[m][1] > 0)
    y, mo = int(first[:4]), int(first[5:7]); o, g, d = [], [], []
    while f"{y:04d}-{mo:02d}" <= last:
        v = p.get(f"{y:04d}-{mo:02d}", (0.0, 0.0, 0))
        o.append(round(v[0])); g.append(round(v[1])); d.append(v[2] if v[2] is not None else 0)
        mo += 1
        if mo > 12: y, mo = y + 1, 1
    return first, o, g, d, r_first
miss = [a for a in list(SUBJ) + sel["offsets"] if a not in prod]
L = [f"# Generated by make_pdp_data.py (Enverus, pulled 2026-11-24; production through {LAST}, the last month all four subject wells report).",
     "# Madison-Hamill 36A-36D 1H-4H (XTO / Exxon, Wolfcamp A, Martin Co TX; first production 2021-09, ~7,100 ft laterals, ~1,700 lb/ft).",
     "# Offsets: Wolfcamp A, lateral midpoint within 5 mi of the subject wells' lateral-midpoint centroid (32.2132, -101.7003),",
     "# first production 2018-01 to 2021-07 (older than the subject wells, so they report at the ages we forecast), lateral >= 5,000 ft,",
     "# proppant >= 1,400 lb/ft. Excluded: " + "; ".join(f"{n} ({w})" for a, n, w in sel["excluded"]) + ".",
     f"# Missing from the production pull: {miss or 'none'}.",
     'DEAL = dict(name="Madison-Hamill 36A-36D PDP", basin="Permian (TX)", deal_type="Working interest", effective="2026-12",',
     '            asking_price=0, operator="XTO ENERGY (EXXON)")',
     f'LAST_MONTH = "{LAST}"',
     "# api: (well, lateral_ft, first_month, oil_bbl[], gas_mcf[], zone, wi, nri, lease_nri)", "SUBJECT = {"]
DAYS = {}
for a, (wi, nri) in SUBJ.items():
    r = off[a]; first, o, g, d, f0 = series(a, LAST); DAYS[a] = d
    L.append(f'"{a}": ({r["WellName"]!r}, {float(r["LateralLength_FT"])}, "{first}", {o}, {g}, {r["ENVInterval"]!r}, {wi}, {nri}, {LEASE_NRI}),')
L += ["}", "# api: (well, lateral_ft, first_month, oil_bbl[], gas_mcf[], zone, distance_mi)", "OFFSETS = {"]
for a in sel["offsets"]:
    if a not in prod: continue
    r = off[a]; first, o, g, d, f0 = series(a, max(prod[a])); DAYS[a] = d
    L.append(f'"{a}": ({r["WellName"]!r}, {float(r["LateralLength_FT"])}, "{first}", {o}, {g}, {r["ENVInterval"]!r}, {float(r["DistanceMi"])}),')
L += ["}", "DAYS = {" + ", ".join(f'"{a}": {d}' for a, d in DAYS.items()) + "}"]
open(os.path.join(H, "pdp_data.py"), "w").write("\n".join(L) + "\n")
print("last month", LAST, "| missing", miss)
for a in SUBJ:
    first, o, g, d, f0 = series(a, LAST); print(off[a]["WellName"], first, "(Enverus first prod", f0, ")", len(o), "months; last 6 oil", o[-6:], "gas", g[-6:])
bad = [(a, off[a]["FirstProdDate"][:7], min(prod[a])) for a in sel["offsets"] if a in prod and min(prod[a]) > off[a]["FirstProdDate"][:7]]
print("offsets whose pull starts after first prod:", bad)
